// Starlight route middleware: title template, Open Graph / Twitter gaps, keywords, and
// JSON-LD structured data (Organization, WebSite, SoftwareApplication, TechArticle,
// BreadcrumbList, FAQPage) for every docs page.

import { defineRouteMiddleware } from '@astrojs/starlight/route-data';
import type { HeadConfig } from '@astrojs/starlight/types';
import { getCollection } from 'astro:content';
import {
	HOME_URL,
	ORG_NAME,
	ORG_URL,
	RELEASES_URL,
	REPO_URL,
	SITE_DESCRIPTION,
	SITE_NAME,
	TAGLINE,
} from '../site.mjs';
import { fileDates } from './git-dates';
import { inlineMarkdownToText } from './inline-md';
import { idToSlug, sectionLabel } from './sections';
import { mainNav } from '../nav/site-nav';
import { OG_CARDS } from './og-cards.mjs';

type HeadEntry = HeadConfig[number];

const SECTION_OG_DIRS = new Set(OG_CARDS.map((c) => c.dir));
const SECTION_OG_ALT: Record<string, string> = Object.fromEntries(OG_CARDS.map((c) => [c.dir, c.alt]));

let slugSet: Promise<Map<string, string>> | undefined;
/** slug -> title, for breadcrumb intermediate levels. */
function knownPages() {
	slugSet ??= getCollection('docs').then(
		(entries) => new Map(entries.map((e) => [idToSlug(e.id), e.data.title as string])),
	);
	return slugSet;
}

const abs = (path: string) => new URL(path.replace(/^\//, ''), HOME_URL).href;
const pageUrl = (slug: string) => abs(slug ? `${slug}/` : '');
const ldJson = (data: unknown) => JSON.stringify(data).replace(/</g, '\\u003c');

function findMeta(head: HeadEntry[], key: 'name' | 'property', value: string) {
	return head.find((h) => h.tag === 'meta' && h.attrs?.[key] === value);
}
function setMeta(head: HeadEntry[], key: 'name' | 'property', value: string, content: string, overwrite = true) {
	const existing = findMeta(head, key, value);
	if (existing) {
		if (overwrite) existing.attrs = { ...existing.attrs, content };
	} else {
		head.push({ tag: 'meta', attrs: { [key]: value, content } });
	}
}

const TITLE_MAX = 60;
const DESCRIPTION_MAX = 160;
const NOT_FOUND_DESCRIPTION =
	'This page does not exist. Find Shadow, the open-source privacy layer for AI, from the docs home, the quick start or the search.';

/**
 * The <title>: `seoTitle` verbatim when set; otherwise "{title} · Shadow — {tagline}" when
 * that fits in 60 characters, then "{title} · Shadow", then the title alone when it already
 * names Shadow (so the brand never appears twice). Titles that are still too long fall back
 * to the part before the first ":" or " — ". Pages whose H1 is long set `seoTitle`.
 */
function documentTitle(title: string, seoTitle: string | undefined, isHome: boolean): string {
	if (seoTitle) return seoTitle;
	if (isHome) return title;
	const hasBrand = new RegExp(`\\b${SITE_NAME}\\b`).test(title);
	const candidates = hasBrand
		? [title]
		: [`${title} · ${SITE_NAME} — ${TAGLINE}`, `${title} · ${SITE_NAME}`];
	const fit = candidates.find((c) => c.length <= TITLE_MAX);
	if (fit) return fit;
	const head = title.split(/: | — /)[0]!.trim();
	return head.includes(SITE_NAME) ? head : `${head} · ${SITE_NAME}`;
}

/** Meta descriptions over 160 characters: whole sentences if enough fit, else cut at a word. */
function clampDescription(text: string): string {
	if (text.length <= DESCRIPTION_MAX) return text;
	const sentences = text.match(/[^.!?]+[.!?]+(\s|$)/g) ?? [];
	let out = '';
	for (const s of sentences) {
		if ((out + s).trim().length > DESCRIPTION_MAX) break;
		out += s;
	}
	if (out.trim().length >= 100) return out.trim();
	const cut = text.slice(0, DESCRIPTION_MAX - 1);
	return `${cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:\s]+$/, '')}…`;
}

export const onRequest = defineRouteMiddleware(async (context) => {
	const route = context.locals.starlightRoute;
	const { entry, head } = route;
	const data = entry.data as typeof entry.data & {
		faq?: { q: string; a: string }[];
		keywords?: string[];
		ogImage?: string;
		seoTitle?: string;
	};
	const slug = idToSlug(route.id ?? '');
	const isHome = slug === '';
	const is404 = slug === '404' || entry.id === '404';

	const fullTitle = documentTitle(data.title, data.seoTitle, isHome);
	const titleTag = head.find((h) => h.tag === 'title');
	if (titleTag) titleTag.content = fullTitle;
	else head.push({ tag: 'title', content: fullTitle });

	const description = is404 ? NOT_FOUND_DESCRIPTION : clampDescription(data.description || SITE_DESCRIPTION);
	setMeta(head, 'name', 'description', description);
	setMeta(head, 'property', 'og:description', description);
	const canonicalHref =
		(head.find((h) => h.tag === 'link' && h.attrs?.rel === 'canonical')?.attrs?.href as string | undefined) ??
		pageUrl(slug);

	// Open Graph and Twitter.
	// Images: the page's own `ogImage`, else one 1200×630 card per top-level section
	// (public/og/<section>.png, generated by scripts/og-images.mjs), else the site card.
	const section = slug.split('/')[0] ?? '';
	const sectionCard = !isHome && !is404 && SECTION_OG_DIRS.has(section) ? `og/${section}.png` : 'og.png';
	const image = data.ogImage ? (/^https?:/.test(data.ogImage) ? data.ogImage : abs(data.ogImage)) : abs(sectionCard);
	const imageAlt =
		sectionCard === 'og.png' || data.ogImage
			? `${SITE_NAME}, the ${TAGLINE}: real values such as jane@acme.com are replaced with realistic fakes before reaching the provider`
			: `${sectionLabel(section)} · ${SITE_NAME} docs: ${SECTION_OG_ALT[section] ?? TAGLINE}`;
	setMeta(head, 'property', 'og:title', fullTitle);
	setMeta(head, 'property', 'og:type', isHome ? 'website' : 'article');
	setMeta(head, 'property', 'og:image', image, false);
	if (!data.ogImage) {
		setMeta(head, 'property', 'og:image:width', '1200', false);
		setMeta(head, 'property', 'og:image:height', '630', false);
		setMeta(head, 'property', 'og:image:type', 'image/png', false);
	}
	setMeta(head, 'property', 'og:image:alt', imageAlt, false);
	setMeta(head, 'name', 'twitter:card', 'summary_large_image');
	setMeta(head, 'name', 'twitter:title', fullTitle);
	setMeta(head, 'name', 'twitter:description', description);
	setMeta(head, 'name', 'twitter:image', image, false);
	setMeta(head, 'name', 'twitter:image:alt', imageAlt, false);
	if (data.keywords?.length) setMeta(head, 'name', 'keywords', data.keywords.join(', '));
	if (is404) setMeta(head, 'name', 'robots', 'noindex');

	// FAQ entries also appear in the on-page table of contents.
	if (data.faq?.length && route.toc && !route.toc.items.some((i) => i.slug === 'faq')) {
		route.toc.items.push({ depth: 2, slug: 'faq', text: 'Frequently asked questions', children: [] });
	}

	if (is404) return;

	// Structured data.
	const orgId = `${HOME_URL}#organization`;
	const siteId = `${HOME_URL}#website`;
	const appId = `${HOME_URL}#software`;
	const sourceId = `${HOME_URL}#source-code`;
	const graph: Record<string, unknown>[] = [
		{
			'@type': 'Organization',
			'@id': orgId,
			name: ORG_NAME,
			url: HOME_URL,
			logo: { '@type': 'ImageObject', url: abs('logo.png'), width: 512, height: 512 },
			sameAs: [ORG_URL],
		},
		{
			'@type': 'WebSite',
			'@id': siteId,
			url: HOME_URL,
			name: `${SITE_NAME} documentation`,
			alternateName: SITE_NAME,
			description: SITE_DESCRIPTION,
			inLanguage: 'en',
			publisher: { '@id': orgId },
		},
		{
			'@type': 'SoftwareApplication',
			'@id': appId,
			name: SITE_NAME,
			description: SITE_DESCRIPTION,
			url: HOME_URL,
			applicationCategory: 'SecurityApplication',
			applicationSubCategory: 'DeveloperApplication',
			featureList: [
				'Reversible, format-preserving PII and secret masking for LLM API requests',
				'Restoration of responses, streams and tool-call arguments',
				'Local HTTPS proxy, gateway base URL and embeddable Rust library',
				'Encrypted local vault; no cloud service, account or telemetry',
			],
			operatingSystem: 'macOS, Linux, Windows',
			softwareRequirements: 'None (single static binary); Rust 1.88+ to build from source',
			license: 'https://www.apache.org/licenses/LICENSE-2.0',
			isAccessibleForFree: true,
			offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
			downloadUrl: RELEASES_URL,
			installUrl: pageUrl('getting-started/installation'),
			softwareHelp: { '@type': 'CreativeWork', url: HOME_URL },
			sameAs: [REPO_URL],
			image: abs('og.png'),
			publisher: { '@id': orgId },
			author: { '@id': orgId },
			isBasedOn: { '@id': sourceId },
		},
		{
			'@type': 'SoftwareSourceCode',
			'@id': sourceId,
			name: `${SITE_NAME} source code`,
			description: SITE_DESCRIPTION,
			url: REPO_URL,
			codeRepository: REPO_URL,
			programmingLanguage: { '@type': 'ComputerLanguage', name: 'Rust' },
			runtimePlatform: 'macOS, Linux, Windows',
			license: 'https://www.apache.org/licenses/LICENSE-2.0',
			isAccessibleForFree: true,
			targetProduct: { '@id': appId },
			author: { '@id': orgId },
			publisher: { '@id': orgId },
		},
	];

	// Breadcrumbs from the URL path; intermediate levels only when a page exists there.
	const pages = await knownPages();
	const crumbs: { name: string; item: string }[] = [{ name: SITE_NAME, item: HOME_URL }];
	if (!isHome) {
		const parts = slug.split('/');
		for (let i = 1; i < parts.length; i++) {
			const sub = parts.slice(0, i).join('/');
			if (pages.has(sub)) crumbs.push({ name: i === 1 ? sectionLabel(sub) : pages.get(sub)!, item: pageUrl(sub) });
		}
		// A section landing page ('compare') is named by its section label, not its long H1.
		const last = parts.length === 1 ? sectionLabel(slug) : data.title;
		crumbs.push({ name: last, item: canonicalHref });
	}
	if (crumbs.length > 1) {
		graph.push({
			'@type': 'BreadcrumbList',
			'@id': `${canonicalHref}#breadcrumb`,
			itemListElement: crumbs.map((c, i) => ({
				'@type': 'ListItem',
				position: i + 1,
				name: c.name,
				item: c.item,
			})),
		});
	}

	const dates = fileDates(entry.filePath);
	if (isHome) {
		graph.push({
			'@type': 'WebPage',
			'@id': `${canonicalHref}#webpage`,
			url: canonicalHref,
			name: data.title,
			description,
			inLanguage: 'en',
			isPartOf: { '@id': siteId },
			about: { '@id': appId },
			mainEntity: { '@id': appId },
			primaryImageOfPage: { '@type': 'ImageObject', url: image },
			dateModified: dates.modified,
		});
	} else {
		graph.push({
			'@type': 'TechArticle',
			'@id': `${canonicalHref}#article`,
			headline: data.title,
			name: data.title,
			description,
			url: canonicalHref,
			mainEntityOfPage: canonicalHref,
			inLanguage: 'en',
			datePublished: dates.published,
			dateModified: dates.modified,
			image,
			isPartOf: { '@id': siteId },
			about: { '@id': appId },
			author: { '@id': orgId },
			publisher: { '@id': orgId },
			...(data.keywords?.length ? { keywords: data.keywords.join(', ') } : {}),
			...(crumbs.length > 1 ? { breadcrumb: { '@id': `${canonicalHref}#breadcrumb` } } : {}),
		});
	}

	if (isHome) {
		// The header's main navigation, for answer engines and rich results.
		const nav = await mainNav();
		const items = [
			{ name: 'Introduction', url: '/getting-started/introduction/' },
			{ name: 'Quick start', url: '/getting-started/quick-start/' },
			{ name: 'Installation', url: '/getting-started/installation/' },
			{ name: 'How it works', url: '/concepts/how-it-works/' },
			{ name: 'Integrations', url: '/integrate/overview/' },
			{ name: 'Benchmarks', url: '/benchmarks/' },
			{ name: nav.solutions.columns[0]?.label ?? 'Use cases', url: '/use-cases/' },
			{ name: nav.industries.label, url: '/industries/' },
			{ name: 'Company size', url: '/company-size/' },
			{ name: 'Compare alternatives', url: '/compare/' },
			{ name: 'Security model', url: '/reference/security/' },
			{ name: 'FAQ', url: '/reference/faq/' },
		];
		graph.push({
			'@type': 'ItemList',
			'@id': `${HOME_URL}#navigation`,
			name: 'Main navigation',
			itemListElement: items.map((it, i) => ({
				'@type': 'SiteNavigationElement',
				position: i + 1,
				name: it.name,
				url: pageUrl(it.url.replace(/^\/|\/$/g, '')),
			})),
		});
	}

	if (data.faq?.length) {
		graph.push({
			'@type': 'FAQPage',
			'@id': `${canonicalHref}#faq`,
			url: canonicalHref,
			inLanguage: 'en',
			isPartOf: { '@id': siteId },
			mainEntity: data.faq.map(({ q, a }) => ({
				'@type': 'Question',
				name: inlineMarkdownToText(q),
				acceptedAnswer: { '@type': 'Answer', text: inlineMarkdownToText(a) },
			})),
		});
	}

	head.push({
		tag: 'script',
		attrs: { type: 'application/ld+json' },
		content: ldJson({ '@context': 'https://schema.org', '@graph': graph }),
	});
});
