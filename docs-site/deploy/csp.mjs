// Builds the Content-Security-Policy for the static site in dist/ and writes it as a
// Caddy snippet or a Cloudflare _headers file. Inline <script> blocks (Starlight's theme and sidebar scripts, Astro's
// small module scripts) are allowed by SHA-256 hash, so no 'unsafe-inline' for scripts.
//
//   node deploy/csp.mjs dist deploy/csp.caddy   # Caddy snippet (self-hosting)
//   node deploy/csp.mjs dist dist/_headers      # Cloudflare Workers static assets
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dist = 'dist', out = 'csp.caddy'] = process.argv.slice(2);
const hashes = new Set();
const walk = (dir) => {
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (statSync(p).isDirectory()) walk(p);
		else if (p.endsWith('.html')) {
			const html = readFileSync(p, 'utf8');
			for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
				const [, attrs, body] = m;
				if (/\bsrc=/.test(attrs) || /type="application\/(ld\+)?json"/.test(attrs) || !body.trim()) continue;
				hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
			}
		}
	}
};
walk(dist);

const policy = [
	"default-src 'self'",
	// 'wasm-unsafe-eval': Pagefind search runs as WebAssembly.
	// static.cloudflareinsights.com: the Cloudflare Web Analytics beacon (src/site.mjs).
	`script-src 'self' 'wasm-unsafe-eval' https://static.cloudflareinsights.com ${[...hashes].sort().join(' ')}`,
	// Inline style attributes (chart widths) and Astro's inlined <style> blocks.
	"style-src 'self' 'unsafe-inline'",
	"img-src 'self' data:",
	"font-src 'self'",
	"connect-src 'self' https://cloudflareinsights.com",
	"manifest-src 'self'",
	"worker-src 'self'",
	"object-src 'none'",
	"base-uri 'self'",
	"form-action 'self'",
	"frame-ancestors 'none'",
	'upgrade-insecure-requests',
].join('; ');

if (out.endsWith('_headers')) {
	// Cloudflare Workers static assets: the same policy and security headers for every path.
	writeFileSync(
		out,
		[
			'/*',
			`  Content-Security-Policy: ${policy}`,
			'  Strict-Transport-Security: max-age=31536000; includeSubDomains',
			'  X-Content-Type-Options: nosniff',
			'  Referrer-Policy: strict-origin-when-cross-origin',
			'  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()',
			'  X-Frame-Options: DENY',
			'/_astro/*',
			'  Cache-Control: public, max-age=31536000, immutable',
			'',
		].join('\n'),
	);
} else {
	writeFileSync(out, `# Generated by deploy/csp.mjs at build time. Do not edit.\nheader Content-Security-Policy "${policy}"\n`);
}
console.log(`CSP: ${hashes.size} inline script hashes -> ${out}`);
