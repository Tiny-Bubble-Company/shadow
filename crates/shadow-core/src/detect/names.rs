/// Lowercase and strip common Latin diacritics, so "Noëlle" matches "Noelle".
pub fn fold(s: &str) -> String {
    s.chars()
        .flat_map(|c| c.to_lowercase())
        .map(|c| match c {
            'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' => 'a',
            'ç' => 'c',
            'è' | 'é' | 'ê' | 'ë' => 'e',
            'ì' | 'í' | 'î' | 'ï' => 'i',
            'ñ' => 'n',
            'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' => 'o',
            'ù' | 'ú' | 'û' | 'ü' => 'u',
            'ý' | 'ÿ' => 'y',
            'ć' | 'č' => 'c',
            'ę' => 'e',
            'ł' => 'l',
            'ń' => 'n',
            'ś' | 'š' => 's',
            'ź' | 'ż' | 'ž' => 'z',
            'ą' => 'a',
            c => c,
        })
        .collect()
}

